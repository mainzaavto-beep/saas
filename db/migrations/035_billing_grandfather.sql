-- 035: существующие кабинеты не должны закрыться при включении блокировки.
-- До появления оплаты у них обе даты пусты, а пустые даты означают «доступ
-- закрыт». Выдаём месяц оплаченного доступа всем кабинетам, созданным до
-- ввода биллинга; новые кабинеты получают триал при онбординге.
UPDATE auth.cabinets
   SET paid_until = now() + interval '30 days'
 WHERE trial_ends_at IS NULL
   AND paid_until IS NULL
   AND created_at < timestamptz '2026-08-08 00:00:00+03';
