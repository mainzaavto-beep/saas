-- 038: отдельная отметка "последняя попытка", не совпадающая с "начало эпизода".
--
-- Фикс-волна 2026-08-07 (находка №2): auth_failed_at раньше перезаписывался
-- на every отказ, включая суточные контрольные попытки — баннер/письмо теряли
-- дату первого отказа и занижали масштаб поломки (клиент, сломанный месяц
-- назад, видел "не обновляется со вчера"). Чиним: auth_failed_at теперь
-- фиксирует НАЧАЛО эпизода (ставится один раз, при переходе ok→failing).
--
-- Но auth_failed_at использовался ещё и в should_skip (worker/shop_auth.py)
-- как "когда были последний раз" — от него отсчитывались сутки паузы между
-- контрольными попытками. Если просто заморозить auth_failed_at, через 24ч
-- после НАЧАЛА эпизода should_skip перестанет пропускать вообще (now -
-- failed_at всегда > 24ч) — пауза сломается, и сломанный магазин снова будет
-- пытаться на каждом прогоне (4×/день) — ровно та проблема, которую чинила
-- миграция 037 (кабинет 1009, 6 отказов Ozon 403 на каждый прогон).
--
-- Поэтому заводим отдельное поле для cadence, auth_failed_at оставляем только
-- для отображения (баннер/письмо).
ALTER TABLE auth.shops ADD COLUMN IF NOT EXISTS auth_last_attempt_at TIMESTAMPTZ;
