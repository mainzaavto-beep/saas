-- 026_warehouse_efficiency.sql — эффективность складов WB.
--
-- Контекст (2026-07-18): на /stocks вкладка «Перевозки» заменяется на
-- «Эффективность складов». Метрики: оборачиваемость (продажи÷остаток) +
-- локальность (по кластеру). Цель — понять, какие склады генерят больше
-- выручки и где товар работает эффективнее, чтобы грузить именно их.
--
-- Источники кластера склада: WB отдаёт поле regionName в ответе
-- POST stocks-report/wb-warehouses (модуль Analytics). Это укрупнённая
-- группировка самого склада (7 кластеров: Центральный, Северо-Западный,
-- Приволжский, Уральский, Дальневосточный и Сибирский, Южный и СКФО,
-- Беларусь, Армения и т.д.). Сборщик wb_references пишет его в колонку region.
--
-- ⚠️ ТЕРМИНОЛОГИЧЕСКАЯ ГРАБЛЯ (зафиксировать!):
-- WB использует ДВЕ разные группировки регионов:
--   • regionName склада (stocks-report) — 7 УКРУПНЁННЫХ кластеров, где
--     Юг+СКФО = «Южный и Северо-Кавказский», Сибирь+ДВ = «Дальневосточный
--     и Сибирский».
--   • okrug_name покупателя (wb_sales/orders) — 8 РАЗДЕЛЬНЫХ ФО РФ
--     («Южный федеральный округ» и «Северо-Кавказский федеральный округ» —
--     раздельно, как и Сибирский/Дальневосточный).
-- Это РАЗНЫЕ сущности с одним смыслом. Карта region_to_cluster ниже
-- согласует их: okrug_name покупателя (или страна СНГ) → укрупнённый cluster,
-- совпадающий с regionName склада. Без карты local_pct считался бы некорректно.
--
-- Идемпотентна (ADD COLUMN IF NOT EXISTS + CREATE IF NOT EXISTS + ON CONFLICT).

-- =====================================================================
--  Колонка region в справочнике складов (кластер из regionName).
-- =====================================================================
ALTER TABLE shared.wb_warehouses ADD COLUMN IF NOT EXISTS region TEXT;

-- is_active / is_transit_active сделать nullable: stocks-report (первичный
-- источник для складов с остатками) не отдаёт эти поля, только /warehouses.
-- При сборке справочника из двух API часть строк приходит без них —
-- NOT NULL блокировал upsert. COALESCE в db_pg.py сохраняет существующее
-- значение, для новых строк остаётся NULL (интерпретируется как «неизвестно»).
ALTER TABLE shared.wb_warehouses ALTER COLUMN is_active DROP NOT NULL;
ALTER TABLE shared.wb_warehouses ALTER COLUMN is_transit_active DROP NOT NULL;

-- =====================================================================
--  Карта okrug_name (ФО покупателя) / страна СНГ → укрупнённый cluster.
--  Покрывает все значения из wb_sales cabinet#1 (8 ФО + Беларусь/Казахстан/
--  Армения через region_name при пустом okrug_name). Fallback 'Прочее'.
-- =====================================================================
CREATE TABLE IF NOT EXISTS shared.region_to_cluster (
    region     TEXT PRIMARY KEY,    -- okrug_name покупателя ИЛИ имя страны/кластера
    cluster    TEXT NOT NULL         -- укрупнённый cluster (совпадает с wb_warehouses.region)
);
GRANT SELECT ON shared.region_to_cluster TO saas_app;

