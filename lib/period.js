// Дефолтное окно панели: последние N дней ПО ВЧЕРА. Сегодняшний день
// финансово всегда недособран (логистика/реклама/сборы начисляются раньше
// выручки) — текущая дата в дефолте занижает прибыль (решение владельца
// 2026-08-25). Ручной выбор периода этим НЕ ограничивается.
// Датировка — UTC-строками, как во всех роутах (договорённость не меняем).
export function defaultPeriod(days = 30) {
  const to = new Date(Date.now() - 864e5).toISOString().slice(0, 10);
  const from = new Date(Date.now() - days * 864e5).toISOString().slice(0, 10);
  return { from, to };
}

// Месячное дефолтное окно: с 1-го числа месяца ПО ВЧЕРА. Если сегодня
// 1-е число, «вчера» — последний день прошлого месяца, и окно само
// становится прошлым месяцем целиком (решение владельца 2026-08-25) —
// отдельной ветки для границы месяца не нужно.
export function defaultMonthPeriod() {
  const to = new Date(Date.now() - 864e5).toISOString().slice(0, 10);
  return { from: to.slice(0, 8) + "01", to };
}
